def arc(head, side_sign, psi0, psi1, n, r, valley):
    """Points on the disc + .0015 m of `head`, angle psi (deg) from the valley direction toward distal."""
    hs, hl, R = HEADS[head]; vs, vl = valley
    c = (hs * SPAN, hl); v = (vs * SPAN, vl); u = (v[0] - c[0], v[1] - c[1]); L = math.hypot(*u); u = (u[0] / L, u[1] / L)
    nn = (-u[1], u[0])
    if nn[0] < 0: nn = (-nn[0], -nn[1])
    out = []
    for k in range(n):
        p = math.radians(psi0 + (psi1 - psi0) * k / (n - 1)); rho = R + .0015
        d = (u[0] * math.cos(p) + nn[0] * math.sin(p), u[1] * math.cos(p) + nn[1] * math.sin(p))
        out.append((round((c[0] + rho * d[0]) / SPAN, 3), round(c[1] + rho * d[1], 4), r[k]))
    return out

V = {"IM": (.975, .028), "MR": (1.005, -.028), "RP": (.922, -.072)}
def fork(a, b, valley, stem, ra, rb, pa=(-8, 22), pb=(-8, 30)):
    """Arm A (head a) runs distal end -> fork, fork = stem[0]; arm B (head b) separate, ends on the fork."""
    A = list(reversed(arc(a, 1, pa[0], pa[1], 3, ra, V[valley])))
    B = list(reversed(arc(b, 1, pb[0], pb[1], 3, rb, V[valley])))
    return A, B

